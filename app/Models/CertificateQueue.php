<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class CertificateQueue extends Model
{
    use HasFactory;

    protected $table = 'certificate_queue';

    protected $fillable = [
        'user_id',
        'course_id',
        'enrollment_id',
        'certificate_type',
        'is_primary',
        'status',
        'auto_approved',
        'certificate_file',
        'certificate_number',
        'certificate_title',
        'certificate_mode',
        'auto_generated_certificate_path',
        'uploaded_certificate_path',
        'rejection_reason',
        'completed_at',
        'reviewed_at',
        'reviewed_by',
        'approved_at',
        'approved_by',
        'rejected_at',
        'all_meetings_attended',
        'meetings_attended_count',
        'total_meetings_count',
    ];

    protected $casts = [
        'completed_at' => 'datetime',
        'reviewed_at' => 'datetime',
        'approved_at' => 'datetime',
        'rejected_at' => 'datetime',
        'all_meetings_attended' => 'boolean',
        'is_primary' => 'boolean',
        'auto_approved' => 'boolean',
    ];

    /**
     * Get the user (student) for this queue entry
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Get the course for this queue entry
     */
    public function course(): BelongsTo
    {
        return $this->belongsTo(Course::class);
    }

    /**
     * Get the enrollment for this queue entry
     */
    public function enrollment(): BelongsTo
    {
        return $this->belongsTo(Enrollment::class);
    }

    /**
     * Get the admin who reviewed this
     */
    public function reviewer(): BelongsTo
    {
        return $this->belongsTo(User::class, 'reviewed_by');
    }

    /**
     * Approve and upload certificate
     */
    public function approve(User $admin, string $certificateFilePath): void
    {
        $this->update([
            'status' => 'approved',
            'certificate_file' => $certificateFilePath,
            'reviewed_at' => now(),
            'reviewed_by' => $admin->id,
        ]);

        // Update enrollment certificate info
        $this->enrollment->update([
            'certificate_issued_at' => now(),
            'certificate_file' => $certificateFilePath,
        ]);
    }

    /**
     * Reject with reason
     */
    public function reject(User $admin, string $reason): void
    {
        $this->update([
            'status' => 'rejected',
            'rejection_reason' => $reason,
            'reviewed_at' => now(),
            'reviewed_by' => $admin->id,
            'rejected_at' => now(),
        ]);
    }

    /**
     * Get certificate file URL
     */
    public function getCertificateFileUrlAttribute(): ?string
    {
        if ($this->certificate_file) {
            return asset('storage/' . $this->certificate_file);
        }
        return null;
    }

    /**
     * Check if pending
     */
    public function isPending(): bool
    {
        return $this->status === 'pending';
    }

    /**
     * Check if approved
     */
    public function isApproved(): bool
    {
        return $this->status === 'approved';
    }

    /**
     * Check if rejected
     */
    public function isRejected(): bool
    {
        return $this->status === 'rejected';
    }

    /**
     * Scope: Only pending entries
     */
    public function scopePending($query)
    {
        return $query->where('status', 'pending');
    }

    /**
     * Scope: Only approved entries
     */
    public function scopeApproved($query)
    {
        return $query->where('status', 'approved');
    }

    /**
     * Scope: Only rejected entries
     */
    public function scopeRejected($query)
    {
        return $query->where('status', 'rejected');
    }

    /**
     * Scope: Only auto-generated certificates
     */
    public function scopeAutoGenerated($query)
    {
        return $query->where('certificate_type', 'auto_generated');
    }

    /**
     * Scope: Only uploaded certificates
     */
    public function scopeUploaded($query)
    {
        return $query->where('certificate_type', 'uploaded');
    }

    /**
     * Scope: Only primary certificates
     */
    public function scopePrimary($query)
    {
        return $query->where('is_primary', true);
    }

    /**
     * Check if auto-generated
     */
    public function isAutoGenerated(): bool
    {
        return $this->certificate_type === 'auto_generated';
    }

    /**
     * Check if uploaded
     */
    public function isUploaded(): bool
    {
        return $this->certificate_type === 'uploaded';
    }

    /**
     * Check if primary certificate
     */
    public function isPrimaryCertificate(): bool
    {
        return $this->is_primary === true;
    }
}
